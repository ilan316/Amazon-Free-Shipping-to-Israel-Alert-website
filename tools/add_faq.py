def json_ld_question(q, a):
    """Format a single FAQ item for JSON-LD insertion (with leading comma)."""
    a_escaped = a.replace('"', '\\"')
    return (
        f',\n'
        f'        {{\n'
        f'          "@type": "Question",\n'
        f'          "name": "{q}",\n'
        f'          "acceptedAnswer": {{\n'
        f'            "@type": "Answer",\n'
        f'            "text": "{a_escaped}"\n'
        f'          }}\n'
        f'        }}'
    )


def html_question(q, a):
    """Format a single FAQ item for HTML insertion."""
    return (
        f'\n        <div class="blog-faq-item">\n'
        f'          <p class="blog-faq-q">{q}</p>\n'
        f'          <p class="blog-faq-a">{a}</p>\n'
        f'        </div>'
    )


def update_file(filepath, faqs):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    # --- JSON-LD: insert before the closing ] of FAQPage mainEntity ---
    # Find position of FAQPage, then find the first "      ]" after it
    faqpage_pos = content.find('"@type": "FAQPage"')
    if faqpage_pos == -1:
        print(f'  SKIP (no FAQPage): {os.path.basename(filepath)}')
        return False

    # Find closing bracket of mainEntity after FAQPage
    bracket_pos = content.find('\n      ]', faqpage_pos)
    if bracket_pos == -1:
        print(f'  SKIP (no closing bracket): {os.path.basename(filepath)}')
        return False

    json_additions = ''.join(json_ld_question(q, a) for q, a in faqs)
    content = content[:bracket_pos] + json_additions + content[bracket_pos:]

    # --- HTML: insert before </section> that closes blog-faq ---
    # Find blog-faq section, then find the first </section> after it
    faq_section_pos = content.find('<section class="blog-faq">')
    if faq_section_pos == -1:
        print(f'  SKIP (no blog-faq section): {os.path.basename(filepath)}')
        return False

    end_section_pos = content.find('\n      </section>', faq_section_pos)
    if end_section_pos == -1:
        print(f'  SKIP (no closing section): {os.path.basename(filepath)}')
        return False

    html_additions = ''.join(html_question(q, a) for q, a in faqs)
    content = content[:end_section_pos] + html_additions + content[end_section_pos:]

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)

    return True


def main():
    updated = 0
    for filename, faqs in NEW_FAQS.items():
        filepath = os.path.join(BLOG_DIR, filename)
        if not os.path.exists(filepath):
            print(f'NOT FOUND: {filename}')
            continue
        success = update_file(filepath, faqs)
        if success:
            print(f'  OK ({len(faqs)} new FAQs): {filename}')
            updated += 1

    print(f'\nDone: {updated}/{len(NEW_FAQS)} files updated.')


if __name__ == '__main__':
    main()
